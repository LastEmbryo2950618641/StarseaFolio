async function visible(locator) { await locator.waitFor({ state: "visible" }) }
async function insideViewport(locator) {
  const box = await locator.boundingBox()
  assert.ok(box, "control has a bounding box")
  const viewport = page.viewportSize()
  assert.ok(box.x >= -1 && box.y >= -1 && box.x + box.width <= viewport.width + 1 && box.y + box.height <= viewport.height + 1,
    `control fits viewport: ${JSON.stringify(box)}`)
}
