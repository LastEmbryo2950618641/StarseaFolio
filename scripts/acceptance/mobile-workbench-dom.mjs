await page.route("**/api/rpc", async (route) => {
  const { method } = route.request().postDataJSON()
  const allowed = /(?:\.get|\.read|\.list|\.resolve|\.resolveByPath|\.findActiveRevision|\.contextUsage|\.streamPeek|\.headMeta|\.paths|\.readAsOf|\.branches|\.neighborhood|\.search|\.open|\.readRevision)$/.test(method)
    || method === "synopsis.conversation.start"
  if (!allowed) {
    forbiddenCalls.push(method)
    await route.abort()
    return
  }
  await route.continue()
})
